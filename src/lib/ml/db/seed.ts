// Idempotent reference-data seed. Node cannot reach the D1 binding, so this script
// upserts the curriculum + quiz content into an in-memory SQLite database (migrated
// from the same drizzle SQL the schema is built from), then writes those rows out as
// a D1 migration in `migrations/`. Apply it with `npm run db:migrate`.
//
// Only reference tables are written. Per-user data (users, quiz_attempts,
// user_progress, playground_state) is never touched here. If the reference content is
// unchanged since the newest reference-data migration, no new file is written.
import fs from "node:fs";
import path from "node:path";
import Database from "better-sqlite3";
import { drizzle } from "drizzle-orm/better-sqlite3";
import { migrate } from "drizzle-orm/better-sqlite3/migrator";
import * as schema from "./schema.sqlite";
import { CURRICULUM } from "../curriculum";
import { QUIZ_SEEDS } from "../quizzes";

const root = process.cwd();
const migrationsDir = path.join(root, "migrations");
const reference = ["chapters", "sections", "quizzes", "questions"] as const;
const primaryKey = "id";

const passThreshold = Number(process.env.ML_QUIZ_PASS_THRESHOLD ?? 0.7);

async function populate(db: ReturnType<typeof drizzle<typeof schema>>): Promise<number> {
  for (const chapter of CURRICULUM) {
    await db
      .insert(schema.chapters)
      .values({ id: chapter.slug, title: chapter.title, summary: chapter.summary, order: chapter.order })
      .onConflictDoUpdate({
        target: schema.chapters.id,
        set: { title: chapter.title, summary: chapter.summary, order: chapter.order },
      });

    for (const section of chapter.sections) {
      const sectionId = `${chapter.slug}/${section.slug}`;
      await db
        .insert(schema.sections)
        .values({ id: sectionId, chapterId: chapter.slug, title: section.title, order: section.order })
        .onConflictDoUpdate({
          target: schema.sections.id,
          set: { chapterId: chapter.slug, title: section.title, order: section.order },
        });
    }
  }

  let questionCount = 0;

  for (const quizSeed of QUIZ_SEEDS) {
    const sectionId = `${quizSeed.chapterSlug}/${quizSeed.sectionSlug}`;
    const quizId = sectionId; // one quiz per section

    await db
      .insert(schema.quizzes)
      .values({ id: quizId, sectionId, passThreshold })
      .onConflictDoUpdate({
        target: schema.quizzes.id,
        set: { sectionId, passThreshold },
      });

    for (const q of quizSeed.questions) {
      const questionId = `${quizId}#${q.order}`;
      const row = {
        quizId,
        order: q.order,
        kind: q.kind,
        prompt: q.prompt,
        options: q.options ?? null,
        correctAnswer: q.correctAnswer,
        tolerance: q.tolerance ?? null,
        explanation: q.explanation,
      };
      await db
        .insert(schema.questions)
        .values({ id: questionId, ...row })
        .onConflictDoUpdate({ target: schema.questions.id, set: row });
      questionCount++;
    }
  }
  return questionCount;
}

function sqlLiteral(value: unknown): string {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return String(value);
  return `'${String(value).replace(/'/g, "''")}'`;
}

/** Renders one upsert per row, so re-running the migration on D1 updates rather than duplicates. */
function renderUpserts(sqlite: Database.Database, table: string): string {
  const rows = sqlite.prepare(`SELECT * FROM "${table}" ORDER BY "${primaryKey}"`).all() as Record<string, unknown>[];
  return rows
    .map((row) => {
      const columns = Object.keys(row);
      const cols = columns.map((c) => `"${c}"`).join(", ");
      const vals = columns.map((c) => sqlLiteral(row[c])).join(", ");
      const updates = columns
        .filter((c) => c !== primaryKey)
        .map((c) => `"${c}" = excluded."${c}"`)
        .join(", ");
      return `INSERT INTO "${table}" (${cols}) VALUES (${vals}) ON CONFLICT("${primaryKey}") DO UPDATE SET ${updates};`;
    })
    .join("\n");
}

function renderReferenceSql(sqlite: Database.Database): string {
  const body = reference.map((t) => renderUpserts(sqlite, t)).join("\n");
  return `-- Generated by src/lib/ml/db/seed.ts. Do not edit by hand; rerun \`npm run db:seed\`.\n${body}\n`;
}

function latestReferenceMigration(): { file: string; number: number } | undefined {
  if (!fs.existsSync(migrationsDir)) return undefined;
  return fs
    .readdirSync(migrationsDir)
    .map((file) => ({ file, match: /^(\d{4})_reference_data\.sql$/.exec(file) }))
    .filter((entry): entry is { file: string; match: RegExpExecArray } => entry.match !== null)
    .map((entry) => ({ file: entry.file, number: Number(entry.match[1]) }))
    .sort((a, b) => b.number - a.number)[0];
}

async function main() {
  const sqlite = new Database(":memory:");
  sqlite.pragma("foreign_keys = ON");
  const db = drizzle(sqlite, { schema });
  migrate(db, { migrationsFolder: path.join(root, "src/lib/ml/db/migrations") });

  const questionCount = await populate(db);
  const sql = renderReferenceSql(sqlite);
  sqlite.close();

  const latest = latestReferenceMigration();
  if (latest && fs.readFileSync(path.join(migrationsDir, latest.file), "utf8") === sql) {
    console.log(`ML Foundations Lab seed unchanged (${latest.file}); no new migration written.`);
    return;
  }

  const nextNumber = (latest?.number ?? 1) + 1;
  const file = `${String(nextNumber).padStart(4, "0")}_reference_data.sql`;
  fs.mkdirSync(migrationsDir, { recursive: true });
  fs.writeFileSync(path.join(migrationsDir, file), sql);

  const sectionCount = CURRICULUM.reduce((n, c) => n + c.sections.length, 0);
  console.log(
    `ML Foundations Lab seed written to migrations/${file}: ${CURRICULUM.length} chapters, ${sectionCount} sections, ${QUIZ_SEEDS.length} quizzes, ${questionCount} questions.`,
  );
}

main().catch((error: unknown) => {
  console.error("ML Foundations Lab seed failed:", error);
  process.exit(1);
});
